const DICTS: Record<Lang, Dict> = { en, bn };

// Bangladesh groups digits in lakhs and crores (12,34,567); bn-BD also writes Bangla digits.
const LOCALE: Record<Lang, string> = { en: "en-IN", bn: "bn-BD" };
const DATE_LOCALE: Record<Lang, string> = { en: "en-GB", bn: "bn-BD" };
const MINUS = "−";

function toBn(n: number) {
  return new Intl.NumberFormat("bn-BD").format(n);
}

export function formatters(lang: Lang) {
  const nf = (frac: number) =>
    new Intl.NumberFormat(LOCALE[lang], { minimumFractionDigits: frac, maximumFractionDigits: frac });
  const num = (x: number, frac = 0) => nf(frac).format(x).replace("-", MINUS);
  return {
    num,
    tk: (x: number) => `${x < 0 ? MINUS : ""}৳${nf(0).format(Math.abs(Math.round(x)))}`,
    pct: (p: number, frac = 0) => `${num(p * 100, frac)}%`,
    signed: (x: number, frac = 0) => (x > 0 ? "+" : "") + num(x, frac),
    // plan dates are calendar days: format them in UTC so no time zone moves them
    day: (iso: string) =>
      new Intl.DateTimeFormat(DATE_LOCALE[lang], {
        weekday: "short",
        day: "numeric",
        month: "short",
        timeZone: "UTC",
      }).format(new Date(`${iso}T00:00:00Z`)),
    dayShort: (iso: string) =>
      new Intl.DateTimeFormat(DATE_LOCALE[lang], { day: "numeric", month: "short", timeZone: "UTC" }).format(
        new Date(`${iso}T00:00:00Z`),
      ),
    dayNum: (iso: string) =>
      new Intl.DateTimeFormat(DATE_LOCALE[lang], { day: "numeric", timeZone: "UTC" }).format(
        new Date(`${iso}T00:00:00Z`),
      ),
    weekdayNarrow: (iso: string) =>
      new Intl.DateTimeFormat(DATE_LOCALE[lang], { weekday: "narrow", timeZone: "UTC" }).format(
        new Date(`${iso}T00:00:00Z`),
      ),
    when: (iso: string) =>
      new Intl.DateTimeFormat(DATE_LOCALE[lang], {
        timeZone: "Asia/Dhaka",
        day: "numeric",
        month: "short",
        hour: "2-digit",
        minute: "2-digit",
        hour12: false,
      }).format(new Date(iso)),
    hour: (h: number) => `${num(h).padStart(2, lang === "bn" ? "০" : "0")}:${lang === "bn" ? "০০" : "00"}`,
    // minutes after midnight as a 24-hour clock time, 09:05
    clock: (min: number) => {
      const m = Math.round(min);
      const pad = (x: number) => num(x).padStart(2, lang === "bn" ? "০" : "0");
      return `${pad(Math.floor(m / 60) % 24)}:${pad(m % 60)}`;
    },
    // a duration in minutes as "1 h 05 min"
    duration: (min: number) => {
      const m = Math.max(0, Math.round(min));
      const h = Math.floor(m / 60);
      const u = lang === "bn" ? { h: "ঘ", m: "মি" } : { h: "h", m: "min" };
      return h ? `${num(h)} ${u.h} ${num(m % 60).padStart(2, lang === "bn" ? "০" : "0")} ${u.m}` : `${num(m)} ${u.m}`;
    },
    ago: (ms: number) => {
      const s = Math.round(ms / 1000);
      const rtf = new Intl.RelativeTimeFormat(DATE_LOCALE[lang], { numeric: "auto", style: "short" });
      if (s < 5) return lang === "bn" ? "এইমাত্র" : "just now";
      if (s < 60) return rtf.format(-s, "second");
      if (s < 3600) return rtf.format(-Math.floor(s / 60), "minute");
      if (s < 86400) return rtf.format(-Math.floor(s / 3600), "hour");
      return rtf.format(-Math.floor(s / 86400), "day");
    },
  };
}

export type Formatters = ReturnType<typeof formatters>;

type LangContext = { lang: Lang; setLang: (l: Lang) => void; t: Dict; f: Formatters };

const Ctx = createContext<LangContext | null>(null);

export function LangProvider({ initial, children }: { initial: Lang; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initial);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    document.cookie = `${LANG_COOKIE}=${l}; path=/; max-age=31536000; samesite=lax`;
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const value = useMemo(() => ({ lang, setLang, t: DICTS[lang], f: formatters(lang) }), [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useLang(): LangContext {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useLang outside LangProvider");
  return ctx;
}
